import numpy as np  # 导入 NumPy 库并重命名为 np，用于数组运算和数值计算

# 1. 数据输入：年龄、薪资（月）、债务（万）
X = np.array([
    [16, 0, 0],
    [24, 5000, 0],
    [23, 6000, 10],
    [28, 5000, 50],
    [40, 15000, 200]
], dtype=float)  # 将训练数据转为浮点数，方便后续标准化和矩阵计算

# 目标输出：0=否，1=是
y = np.array([0, 1, 1, 0, 1], dtype=float)  # 标签数据，表示是否获批

# 自己的数据
me = np.array([[50, 12000, 30]], dtype=float)  # 待预测的单条样本数据


# 2. 数据标准化
# 不标准化的话，薪资数值远大于年龄、债务，梯度更新时薪资这一列会过度影响训练。
mean = X.mean(axis=0)  # 计算每一列特征的均值，axis=0 表示按列统计
std = X.std(axis=0)  # 计算每一列特征的标准差，axis=0 表示按列统计

X_scaled = (X - mean) / std  # 对训练数据进行标准化，使每列大致变成均值 0、标准差 1
me_scaled = (me - mean) / std  # 预测样本必须使用训练集的 mean/std 做同样标准化，保证特征尺度一致


# 3. sigmoid 激活函数
def sigmoid(x):
    # sigmoid(x)=1/(1+e^-x)，把任意实数压缩到 0~1 之间。
    # 在这里可以理解为“获批概率”：越接近 1 越倾向于批准，越接近 0 越倾向于不批准。
    return 1 / (1 + np.exp(-x))


# 4. 初始化权重和偏置
np.random.seed(0)  # 固定随机种子，使每次运行得到相同的初始权重，方便复现实验结果
weights = np.random.randn(3)  # 随机初始化 3 个权重，分别对应年龄、薪资、债务这 3 个特征
bias = 0.0  # 初始化偏置为 0，偏置相当于整体判断门槛
# 随机初始化的目的：让模型从一个非固定的起点开始学习各个特征的重要性。


# 5. 梯度下降训练
# 说明：严格说，这段代码不是“原始感知机更新规则”，而是“sigmoid 二分类模型 + 交叉熵损失 + 批量梯度下降”。
# 原始感知机通常按分错样本逐个更新；这里每一轮都会用全部训练样本计算平均梯度，再统一更新 weights 和 bias。
def train(X, y, weights, bias, lr=0.1, epochs=5000):
    # X 的形状是 (样本数, 特征数)，本例为 (5, 3)。
    # y 的形状是 (样本数,)，本例为 (5,)。
    # weights 的形状是 (特征数,)，本例为 (3,)。
    # bias 是一个标量。
    # lr 是学习率，控制每次沿梯度反方向走多大一步。
    # epochs 是训练轮数，表示完整重复“预测 -> 算梯度 -> 更新参数”的次数。
    n = len(y)  # 样本数量，本例中 n=5

    # 外层循环：训练 epochs 轮。
    # 每一轮都使用全部 5 条样本计算一次平均梯度，所以这是批量梯度下降 Batch Gradient Descent。
    for epoch in range(epochs):
        # 第 1 步：前向计算线性部分 z = X·w + b。
        # np.dot(X, weights) 会把每条样本的 3 个特征分别乘以 3 个权重再相加。
        # 得到的 z 形状是 (5,)，也就是每条样本一个线性打分。
        z = np.dot(X, weights) + bias

        # 第 2 步：把线性打分 z 送入 sigmoid，得到 0~1 之间的预测概率。
        # y_pred[i] 表示第 i 条样本被预测为“获批=1”的概率。
        y_pred = sigmoid(z)

        # 第 3 步：计算预测误差。
        # 对 sigmoid + 交叉熵损失来说，损失函数对 z 的偏导刚好可以化简为 y_pred - y。
        # error > 0 表示预测偏高了，需要把相关权重往降低预测概率的方向调；
        # error < 0 表示预测偏低了，需要把相关权重往提高预测概率的方向调。
        error = y_pred - y

        # 第 4 步：计算权重梯度 dw。
        # X.T 的形状是 (3, 5)，error 的形状是 (5,)。
        # np.dot(X.T, error) 会把所有样本在每个特征上的“误差贡献”加起来，得到 3 个权重各自的梯度。
        # 除以 n 是取平均，使梯度大小不随样本数量直接变大。
        dw = np.dot(X.T, error) / n

        # 第 5 步：计算偏置梯度 db。
        # bias 对每条样本的 z 都加同一个常数，所以它的梯度就是所有样本 error 的平均值。
        db = np.sum(error) / n

        # 第 6 步：沿着梯度的反方向更新参数。
        # 梯度指向“损失上升最快”的方向，所以要用 -=，让损失下降。
        # lr 越大，每次更新越激进；lr 太大可能震荡，太小会学得很慢。
        weights -= lr * dw
        bias -= lr * db

        # 第 7 步：每 1000 轮输出一次当前损失，观察训练是否在变好。
        # 这里使用二分类交叉熵损失：
        #   - y=1 时，希望 y_pred 越接近 1 越好，对应 -log(y_pred)
        #   - y=0 时，希望 y_pred 越接近 0 越好，对应 -log(1-y_pred)
        # 加 1e-8 是为了避免 log(0) 导致数值错误。
        if epoch % 1000 == 0:
            loss = -np.mean(y * np.log(y_pred + 1e-8) + (1 - y) * np.log(1 - y_pred + 1e-8))
            print(f"第{epoch}次训练，loss={loss:.4f}")

    # 循环结束后，返回经过 5000 次梯度下降更新后的权重和偏置。
    return weights, bias


# 调用 train 开始训练：传入标准化后的训练数据、标签、初始权重和初始偏置。
# 返回值会覆盖原来的 weights 和 bias，后面预测时使用的就是训练好的参数。
weights, bias = train(X_scaled, y, weights, bias)

print("\n最终权重：", weights)  # 输出训练得到的 3 个权重，分别对应年龄、薪资、债务
print("最终偏置：", bias)  # 输出训练得到的偏置


# 6. 判断自己是否获批
# 预测阶段只做前向计算，不再计算梯度，也不再更新参数。
prob = sigmoid(np.dot(me_scaled, weights) + bias)  # 计算自己的获批概率

print("\n自己获批概率：", prob[0])  # 输出预测概率

if prob[0] >= 0.5:  # 设定阈值 0.5，概率大于等于 0.5 判为批准
    print("预测结果：批准")
else:
    print("预测结果：不批准")  # 概率小于 0.5 判为不批准
